"""exp16_minply_sweep.py -- Buckling factor versus ply count (paper Table `tab:minply`).

THE generator of `tab:minply`. Before this script existed, that table had no identifiable
source in the bundle: the pre-submission audit (finding B1, 2026-07-20) and the internal
referee report (M2, 2026-07-20) established that its published N=40 column was assembled from
heterogeneous artefacts -- C2/C3 matched the *means* of exp4 (2.402/2.025, not its bests
2.5278/2.2421), while C1 matched the 2-seed sweep of exp3 (4.612) -- under a caption that
claimed "best of 30 seeds". This script replaces that table with a single, versioned,
re-runnable artefact whose caption states the budget it actually used.

What it sweeps: the buckling constraint ALONE (no strength / displacement / delamination /
frequency gate), which is what the table is for -- it exposes the buckling floor of each load
case. Feasible delivered designs come from exp3/exp3b instead, and need not agree with a
tabulated N.

  cases      C1 pure axial, C2 pure shear, C3 axial+shear   (optimisers.constrained_search.CASES)
  alphabet   extended {0,+/-30,+/-45,+/-60,90}              (ALPHABETS["set2"])
  grid       N = 24, 32, 40, 44, 48, 52, 56  (coarse: every 8 plies to 40, every 4 thereafter)
  budget     guided GA, population 40, 24 generations, SEEDS independent seeds (default 5)
  target     BLF >= 4 at load scale 1.0

Reported per grid point: best, mean and std over the seeds, plus every per-seed value -- so
the table can be labelled truthfully whichever statistic it prints, and neither can be
confused with the other again.

Usage (a 32-core machine with ccx 2.21):
    PYTHONPATH=$PWD NPROC=30 SEEDS=5 CCX_BIN=ccx python3 experiments/exp16_minply_sweep.py

Outputs:
    data/exp16_minply_sweep.json        the artefact (checkpointed after every grid point)
    data/tab_minply_generated.tex       the LaTeX table body pasted into the manuscript
"""
from __future__ import annotations

import json
import os
import random
import statistics
import time
import multiprocessing as mp

from optimisers.constrained_search import ga_best, CASES, ALPHABETS

POP, GENS = 40, 24
N_SEEDS = int(os.environ.get("SEEDS", "5"))
GRID = [24, 32, 40, 44, 48, 52, 56]
CASE_ORDER = ["c1_axial", "c2_side", "c3_combo"]
CASE_LABEL = {"c1_axial": "C1 axial", "c2_side": "C2 shear", "c3_combo": "C3 axial+shear"}
TARGET_BLF = 4.0
ALPHABET = "set2"


def sweep_point(case_name: str, n: int, pool) -> dict:
    """Run N_SEEDS independent guided-GA runs at ply count `n`; keep every seed's result."""
    case = CASES[case_name]
    alpha = ALPHABETS[ALPHABET]
    per_seed = []
    for seed in range(1, N_SEEDS + 1):
        bf, seq = ga_best(case, n, alpha, pool, random.Random(seed), pop=POP, gens=GENS, guided=True)
        per_seed.append({"seed": seed, "buckling": round(bf, 4),
                         "half_stack": (seq[: len(seq) // 2] if seq else None)})
    # Il filtro `> 0` scartava in silenzio i seed andati male (la vecchia sentinella -1.0 di
    # buckling_factor, ora sostituita da un'eccezione) E un eventuale primo fattore NEGATIVO
    # genuino, che nei casi a taglio e' fisicamente possibile: due cose diverse, stesso destino.
    # La media "su 5 seed" della tabella poteva quindi essere una media su meno seed senza che
    # la tabella lo dicesse. Ora l'esclusione e' contata e finisce nel JSON.
    vals = [r["buckling"] for r in per_seed if r["buckling"] > 0]
    n_excluded = len(per_seed) - len(vals)
    if n_excluded:
        print(f"  !! N={n}: {n_excluded}/{len(per_seed)} seed esclusi dalle statistiche "
              f"(buckling <= 0): la media NON e' su {len(per_seed)} seed", flush=True)
    return {
        "n_plies": n,
        "n_seeds_used": len(vals),
        "n_seeds_excluded": n_excluded,
        "best": round(max(vals), 4) if vals else None,
        "mean": round(statistics.fmean(vals), 4) if vals else None,
        "std": round(statistics.pstdev(vals), 4) if len(vals) > 1 else 0.0,
        "meets_target": bool(vals and max(vals) >= TARGET_BLF),
        "per_seed": per_seed,
    }


def latex_table(results: dict) -> str:
    """Emit the manuscript table body from the artefact -- no hand-copied numbers."""
    head = " & ".join(str(n) for n in GRID)
    lines = [
        "% GENERATED by experiments/exp16_minply_sweep.py -- do not edit by hand.",
        "% Source artefact: code/data/exp16_minply_sweep.json",
        "\\begin{tabular}{lccccccc}",
        "\\toprule",
        f"$N$ (plies) & {head} \\\\",
        "\\midrule",
    ]
    for case in CASE_ORDER:
        rows = results["sweeps"][case]
        first_meet = next((r["n_plies"] for r in rows if r["meets_target"]), None)
        cells = []
        for r in rows:
            cell = f"{r['best']:.2f}"
            if r["n_plies"] == first_meet:
                cell += "\\,(meet)"
            cells.append(cell)
        lines.append(f"{CASE_LABEL[case]} (GA best) & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.abspath(os.path.join(here, "..", "data"))
    os.makedirs(data_dir, exist_ok=True)
    out_path = os.path.join(data_dir, "exp16_minply_sweep.json")
    tex_path = os.path.join(data_dir, "tab_minply_generated.tex")

    nproc = int(os.environ.get("NPROC", str(os.cpu_count())))
    pool = mp.get_context("fork").Pool(nproc)
    t_start = time.time()
    results = {
        "config": {"pop": POP, "gens": GENS, "n_seeds": N_SEEDS, "seeds": list(range(1, N_SEEDS + 1)),
                   "grid": GRID, "alphabet": ALPHABET, "orientations": ALPHABETS[ALPHABET],
                   "target_BLF": TARGET_BLF, "load_scale": 1.0, "constraint": "buckling only",
                   "nproc": nproc, "ccx": __import__("fe.ccx_bin", fromlist=["resolved"]).resolved()},
        "load_cases": {c: CASES[c] for c in CASE_ORDER},
        "sweeps": {},
    }
    try:
        for case_name in CASE_ORDER:
            results["sweeps"][case_name] = []
            for n in GRID:
                t0 = time.time()
                r = sweep_point(case_name, n, pool)
                r["secs"] = round(time.time() - t0)
                results["sweeps"][case_name].append(r)
                json.dump(results, open(out_path, "w"), indent=1)   # checkpoint every point
                print(f"[{CASE_LABEL[case_name]}] N={n}: best={r['best']} mean={r['mean']} "
                      f"std={r['std']} meet={r['meets_target']} [{r['secs']}s]", flush=True)
    finally:
        pool.close()
        pool.join()

    results["total_secs"] = round(time.time() - t_start)
    json.dump(results, open(out_path, "w"), indent=1)
    open(tex_path, "w").write(latex_table(results))
    print(f"\nJSON -> {out_path}\nTeX  -> {tex_path}   total {results['total_secs']}s", flush=True)


if __name__ == "__main__":
    main()
